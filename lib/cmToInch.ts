const CM_MIN = 10;
const CM_MAX = 127;

export function cmToInch(cm: number): number {
  const clamped = Math.min(Math.max(cm, CM_MIN), CM_MAX);
  const rounded = Math.round(clamped * 2) / 2; // নিকটতম 0.5cm-এ round
  const index = Math.round((rounded - CM_MIN) * 2);
  return CM_TO_INCH_TABLE[index];
}
